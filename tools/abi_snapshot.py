#!/usr/bin/env python3
"""ABI freeze check for include/sco_api.h (the plugin ABI, version 1.1).

sco_api.h 1.1 was released in sdk-v1.1.0 and must not change in a way that breaks a plugin
built against it. tests/abi_v1.c pins it with static asserts at compile time; this tool pins
the same surface as data, so a PR that edits the pins *and* the header together still has to
update a golden file by hand, in the same PR.

The snapshot is the *semantic* surface, taken from a compiled program (sizeof, alignment,
offsetof, enum values, macros): sco_api.h carries comments that have changed since sdk-v1.1.0
(its licence note), so its bytes are deliberately not what is pinned. What is pinned byte for
byte is the released header itself, by sha256, recorded in the golden.

  tools/abi_snapshot.py check [--bin EXE] [--cc CC] [--include DIR] [--root DIR]
      Compile the probe (or run an already built one), compare its output with the golden,
      print the diff and exit 1 on any difference. Also checks the released header's sha256.
  tools/abi_snapshot.py gen OUT.c
      Write the probe program (used by CMakeLists.txt, which builds it with the project's
      own C compiler, MSVC included, and only runs it from CTest).
  tools/abi_snapshot.py emit [--bin EXE] [--cc CC] [--include DIR]
      Print the current surface on stdout. To bless a diff, copy it into the golden by hand
      in the same PR as the header change; there is no mode that writes the golden for you.

Usage from tools/test.sh:   python3 tools/abi_snapshot.py check --cc "$CC"
Usage from CTest:           python3 tools/abi_snapshot.py check --bin <built probe>
"""
import argparse
import difflib
import hashlib
import os
import shutil
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GOLDEN = os.path.join(ROOT, "tests", "abi", "sco_api-v1.1.golden")
TAG = "sdk-v1.1.0"
RELEASED = "include/sco_api.h"

# The frozen surface: every public struct's size, alignment and field offsets, every enum
# value and size, the version macros, the calling-convention macro, the sco_api function
# pointer order, and the reserved padding fields. A line per item, in this order.
PROBE = r'''/* Generated by tools/abi_snapshot.py (`abi_snapshot.py gen`); do not edit or commit.
 * Prints the frozen semantic surface of sco_api.h. tools/abi_snapshot.py compares it with
 * tests/abi/sco_api-v1.1.golden. Plain C11, no sco-core header but sco_api.h. */
#include <stddef.h>
#include <stdint.h>
#include <stdio.h>

#include "sco_api.h"

/* Alignment: _Alignof is C11, and every compiler here is C11 (clang, gcc, MSVC). */
#define ALIGN_OF(t) _Alignof(t)

#define P_SIZE(t)     printf("sizeof %s %lld\n", #t, (long long)sizeof(t))
#define P_ALIGN(t)    printf("alignof %s %lld\n", #t, (long long)ALIGN_OF(t))
#define P_OFF(t, f)   printf("offset %s.%s %lld\n", #t, #f, (long long)offsetof(t, f))
#define P_ENUM(v)     printf("enum %s %lld\n", #v, (long long)(v))
#define P_MACRO(m)    printf("macro %s %lld\n", #m, (long long)(m))
#define P_FN(n, f)    printf("fn %d %s %lld\n", (n), #f, (long long)offsetof(sco_api, f))

/* The three exports' signatures (sco_plugin_query/load/unload) are pinned by tests/abi_v1.c,
 * which compiles the same assignment without linking; a probe program cannot take their
 * addresses without also defining them. */

int main(void) {

    /* 64-bit only: the layout below is the x64 one. */
    P_SIZE(void*);
    P_SIZE(void (*)(void));

    /* Version macros. */
    P_MACRO(SCO_API_MAJOR);
    P_MACRO(SCO_API_MINOR);

    /* Calling convention: its spelling is the platform's (__declspec(dllexport) on Windows,
     * default visibility on gcc/clang), so only that it is defined is pinned here; the three
     * exports carrying it are pinned by the declarations above and by tests/abi_v1.c. */
#ifdef SCO_EXPORT
    printf("macro SCO_EXPORT defined 1\n");
#else
    printf("macro SCO_EXPORT defined 0\n");
#endif

    /* sco_result: values and size (every enum is 4 bytes; the _FORCE32 member pins it). */
    P_SIZE(sco_result);
    P_ENUM(SCO_OK);
    P_ENUM(SCO_UNAVAILABLE);
    P_ENUM(SCO_NOT_FOUND);
    P_ENUM(SCO_BAD_ARG);
    P_ENUM(SCO_CRASHED);
    P_ENUM(SCO_WRONG_THREAD);
    P_ENUM(SCO_TOO_MANY);
    P_ENUM(SCO_FAILED);
    P_ENUM(SCO_RESULT_FORCE32);

    P_SIZE(sco_log_level);
    P_ENUM(SCO_LOG_INFO);
    P_ENUM(SCO_LOG_WARN);
    P_ENUM(SCO_LOG_ERROR);
    P_ENUM(SCO_LOG_FORCE32);

    P_SIZE(sco_arg_type);
    P_ENUM(SCO_ARG_INT);
    P_ENUM(SCO_ARG_FLOAT);
    P_ENUM(SCO_ARG_STRING);
    P_ENUM(SCO_ARG_BOOL);
    P_ENUM(SCO_ARG_FORCE32);

    /* sco_arg: frozen for major 1 (its 8-byte union holds every argument type). */
    P_SIZE(sco_arg);
    P_ALIGN(sco_arg);
    P_OFF(sco_arg, type);
    P_OFF(sco_arg, _pad);
    P_OFF(sco_arg, v);
    P_OFF(sco_arg, v.i);
    P_OFF(sco_arg, v.f);
    P_OFF(sco_arg, v.s);

    /* sco_arg_def: grows at the end, read with sco_command.arg_def_size. */
    P_SIZE(sco_arg_def);
    P_ALIGN(sco_arg_def);
    P_OFF(sco_arg_def, name);
    P_OFF(sco_arg_def, type);
    P_OFF(sco_arg_def, _pad);
    P_OFF(sco_arg_def, help);

    P_SIZE(sco_command);
    P_ALIGN(sco_command);
    P_OFF(sco_command, size);
    P_OFF(sco_command, _pad0);
    P_OFF(sco_command, name);
    P_OFF(sco_command, title);
    P_OFF(sco_command, help);
    P_OFF(sco_command, capability);
    P_OFF(sco_command, args);
    P_OFF(sco_command, nargs);
    P_OFF(sco_command, arg_def_size);
    P_OFF(sco_command, fn);
    P_OFF(sco_command, ctx);

    /* sco_api: the host table. Every field offset, then the function pointer order on its
     * own, so a reorder shows up even where offsets alone could not tell. */
    P_SIZE(sco_api);
    P_ALIGN(sco_api);
    P_OFF(sco_api, size);
    P_OFF(sco_api, major);
    P_OFF(sco_api, minor);
    P_OFF(sco_api, host_version);
    P_OFF(sco_api, has);
    P_OFF(sco_api, run_on_game_thread);
    P_OFF(sco_api, subscribe);
    P_OFF(sco_api, unsubscribe);
    P_OFF(sco_api, status);
    P_OFF(sco_api, log);
    P_OFF(sco_api, register_command);
    P_OFF(sco_api, invoke);
    P_OFF(sco_api, list_commands);
    P_OFF(sco_api, provide_service);
    P_OFF(sco_api, query_service);
    P_OFF(sco_api, release_service);
    P_OFF(sco_api, invoke_raw);
    P_OFF(sco_api, register_raw);
    P_FN(1, host_version);
    P_FN(2, has);
    P_FN(3, run_on_game_thread);
    P_FN(4, subscribe);
    P_FN(5, unsubscribe);
    P_FN(6, status);
    P_FN(7, log);
    P_FN(8, register_command);
    P_FN(9, invoke);
    P_FN(10, list_commands);
    P_FN(11, provide_service);
    P_FN(12, query_service);
    P_FN(13, release_service);
    P_FN(14, invoke_raw);
    P_FN(15, register_raw);

    P_SIZE(sco_plugin_info);
    P_ALIGN(sco_plugin_info);
    P_OFF(sco_plugin_info, size);
    P_OFF(sco_plugin_info, api_major);
    P_OFF(sco_plugin_info, api_minor);
    P_OFF(sco_plugin_info, name);
    P_OFF(sco_plugin_info, version);
    P_OFF(sco_plugin_info, author);

    return 0;
}
'''


def die(msg):
    print("abi_freeze: FAIL " + msg, file=sys.stderr)
    return 1


def run(cmd, cwd=None):
    p = subprocess.run(cmd, cwd=cwd, capture_output=True)
    return p.returncode, p.stdout, p.stderr


def surface(binary=None, cc=None, include=None, work=None):
    """The probe's normalized output: non-empty lines, no trailing whitespace."""
    if binary:
        rc, out, err = run([binary])
        if rc != 0:
            return None, "probe exited %d: %s" % (rc, err.decode("utf-8", "replace").strip())
        text = out.decode("utf-8", "replace")
    else:
        include = include or os.path.join(ROOT, "include")
        cc = cc or os.environ.get("CC") or shutil.which("clang") or shutil.which("cc") or "cc"
        work = work or tempfile.mkdtemp(prefix="abi_freeze_")
        src = os.path.join(work, "abi_freeze_probe.c")
        exe = os.path.join(work, "abi_freeze_probe")
        with open(src, "w", encoding="utf-8") as f:
            f.write(PROBE)
        rc, _, err = run([cc, "-std=c11", "-I", include, "-o", exe, src])
        if rc != 0:
            return None, "could not build the probe with %s:\n%s" % (
                cc, err.decode("utf-8", "replace").strip())
        rc, out, err = run([exe])
        if rc != 0:
            return None, "probe exited %d: %s" % (rc, err.decode("utf-8", "replace").strip())
        text = out.decode("utf-8", "replace")
    return [ln.rstrip() for ln in text.splitlines() if ln.strip()], None


def golden_lines(path=None):
    path = path or GOLDEN
    try:
        with open(path, encoding="utf-8") as f:
            text = f.read()
    except OSError as e:
        return None, None, str(e)
    lines = [ln.rstrip() for ln in text.splitlines()]
    sha = None
    for ln in lines:
        if ln.startswith("# released-sha256 "):
            sha = ln.split()[-1]
    body = [ln for ln in lines if ln.strip() and not ln.lstrip().startswith("#")]
    return body, sha, None


def released_header(root=None):
    """The bytes of include/sco_api.h as released at TAG, or (None, why)."""
    root = root or ROOT
    frozen = os.path.join(root, "tests", "abi", "released", "sco_api.h")
    is_checkout = False
    if shutil.which("git"):
        git_rc, git_root, _ = run(["git", "-C", root, "rev-parse", "--show-toplevel"])
        is_checkout = git_rc == 0 and os.path.realpath(git_root.decode().strip()) == os.path.realpath(root)
    if not is_checkout and os.path.isfile(frozen):
        with open(frozen, "rb") as f:
            return f.read(), None
    cmd = ["git", "-C", root, "show", "%s:%s" % (TAG, RELEASED)]
    rc, out, err = run(cmd)
    if rc != 0:
        # A shallow or tag-less checkout (CI's default) carries no tags: fetch just this one.
        fetch = ["git", "-C", root, "fetch", "--quiet", "--depth", "1", "origin",
                 "tag", TAG]
        if run(fetch)[0] != 0:
            return None, "git show %s:%s failed and so did fetching it (%s)" % (
                TAG, RELEASED, err.decode("utf-8", "replace").strip())
        rc, out, err = run(cmd)
        if rc != 0:
            return None, "git show %s:%s failed: %s" % (
                TAG, RELEASED, err.decode("utf-8", "replace").strip())
    return out, None


def check_released(root, want):
    """The released header's sha256 must be the one the golden records."""
    data, err = released_header(root)
    if err:
        return err
    got = hashlib.sha256(data).hexdigest()
    if got != want:
        return ("the golden records sha256 %s for %s:%s, but that tag's header hashes to %s"
                % (want, TAG, RELEASED, got))
    return None


def main(argv):
    ap = argparse.ArgumentParser(description="ABI freeze check for sco_api.h 1.1")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def common(p):
        p.add_argument("--root", default=ROOT, help="repository root")
        p.add_argument("--include", default=None, help="include dir (default: <root>/include)")
        p.add_argument("--bin", default=None, help="an already built probe to run")
        p.add_argument("--cc", default=None, help="C compiler to build the probe with")
        p.add_argument("--work", default=None, help="where to build the probe")

    common(sub.add_parser("check", help="compare the surface with the golden"))
    common(sub.add_parser("emit", help="print the current surface on stdout"))
    g = sub.add_parser("gen", help="write the probe program")
    g.add_argument("out")
    r = sub.add_parser("released-header", help="write the released header, sha-checked")
    r.add_argument("out")
    r.add_argument("--root", default=ROOT)
    r.add_argument("--golden", default=None)
    a = ap.parse_args(argv)

    if a.cmd == "gen":
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(PROBE)
        print("abi_freeze: wrote %s" % a.out)
        return 0

    if a.cmd == "released-header":
        data, err = released_header(a.root)
        if err:
            return die(err)
        _, want, gerr = golden_lines(a.golden)
        if gerr or not want:
            return die("no '# released-sha256 <hex>' line in %s" % (a.golden or GOLDEN))
        got = hashlib.sha256(data).hexdigest()
        if got != want:
            return die("the golden records sha256 %s for %s:%s, but that tag's header hashes to %s"
                       % (want, TAG, RELEASED, got))
        os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
        with open(a.out, "wb") as f:
            f.write(data)
        print("abi_freeze: wrote %s (%s:%s, sha256 %s)" % (a.out, TAG, RELEASED, got))
        return 0

    lines, err = surface(a.bin, a.cc, a.include, a.work)
    if err:
        return die(err)

    if a.cmd == "emit":
        print("\n".join(lines))
        return 0

    body, want, gerr = golden_lines()
    if gerr:
        return die("cannot read %s: %s" % (GOLDEN, gerr))
    if body != lines:
        print("abi_freeze: FAIL the compiled surface of include/sco_api.h differs from %s"
              % os.path.relpath(GOLDEN, ROOT))
        for ln in difflib.unified_diff(body, lines, "golden", "compiled", lineterm="", n=1):
            print(ln)
        print("abi_freeze: no auto-update. If this is a deliberate 1.x addition, edit the golden "
              "by hand in the same PR (tools/abi_snapshot.py emit prints the new surface) and say "
              "why in the PR. Anything else is a break of the released ABI.")
        return 1
    print("abi_freeze: sco_api.h 1.1 surface matches %s (%d items)"
          % (os.path.relpath(GOLDEN, ROOT), len(lines)))

    err = check_released(a.root, want)
    if err:
        return die(err)
    print("abi_freeze: %s:%s hashes to the sha256 the golden records (%s)" % (TAG, RELEASED, want))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
