Result Host::Poll(uint64_t now) {
    auto& s=*state_;if(!s.map.base)return Result::Disabled;
    if(!s.Admitted()){Stop();s.capture.Stop();return Result::Disabled;}
    auto fail=[&](Result r){s.Ack(0,{},now,"refused");Stop();return r;};
    if(now<s.lastNow||now>kMaxMonotonicMs)return fail(Result::Corrupt);s.lastNow=now;
    auto geometry=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(geometry!=Result::Ok)return fail(geometry);
    sc_ipc_owner_beat(&s.channel,now);
    if(s.phase==1&&now>s.handshakeDeadline)return fail(Result::Deadline);
    // A response not consumed yet means one read remains outstanding. No pipelining.
    const uint64_t queued=sc_ipc_i_ld64(&s.request.ring->pushed)-sc_ipc_i_ld64(&s.request.ring->popped);
    if(queued==0)return Result::Ok;
    if(s.phase==2&&sc_ipc_i_ld64(&s.response.ring->head)!=sc_ipc_i_ld64(&s.response.ring->tail))return fail(Result::Busy);
    Frame f;auto r=Pop(s.request,s.phase==0?s.credentials.secret:s.peerKey,f,kRequest);
    if(r!=Result::Ok)return fail(r);
    if(f.session!=s.credentials.session||f.epoch!=s.credentials.epoch)return fail(Result::Epoch);
    if(f.deadline<now||f.deadline-now>2000)return fail(Result::Deadline);
    s.ackDeadline=f.deadline;
    if(!Coordinates(f,s.credentials,1,s.phase==0?0:s.nextPeer,now))return fail(Result::Auth);
    json::Object input;if(!json::Parse(f.payload,input))return fail(Result::Corrupt);
    if(s.phase==0){
        if(f.opcode!=1||!json::Control(1,input))return fail(Result::Auth);
        if(now-s.authStart>=60000){s.authStart=now;s.authCount=0;}if(++s.authCount>5)return fail(Result::Rate);
        const auto nonce=input.strings.at("client_nonce");
        if(s.nonces.size()>=4096||s.nonces.count(nonce)||!Unhex(nonce,s.client.data(),32)||Zero(s.client.data(),32))return fail(Result::Auth);
        s.nonces.insert(nonce);
        if((input.nulls.count("expected_host_build")!=size_t(!s.credentials.build))||
           (s.credentials.build&&input.strings.at("expected_host_build")!=*s.credentials.build))return fail(Result::Auth);
        if(!platform::Random(s.host.data(),32)||Zero(s.host.data(),32)||s.host==s.client)return fail(Result::Auth);
        Derive(s.credentials,s.client,s.host,s.peerKey,s.hostKey);s.handshakeId=f.request;s.handshakeDeadline=f.deadline;
        Frame reply=f;reply.opcode=2;reply.direction=2;
        auto payload=Transcript(s.client,s.host);payload.pop_back();reply.payload=payload+",\"host_build\":"+Build(s.credentials)+"}";
        if(!s.Ack(1,f.request,now,"challenge")||!Push(s.response,reply,s.credentials.secret))return fail(Result::Audit);
        s.phase=1;return Result::Ok;
    }
    if(s.phase==1){
        if(f.opcode!=3||f.request!=s.handshakeId||f.deadline!=s.handshakeDeadline||!json::Control(3,input)||!Echo(input,s.client,s.host))return fail(Result::Auth);
        Frame reply=f;reply.opcode=4;reply.direction=2;reply.payload=Transcript(s.client,s.host);
        if(!s.Ack(3,f.request,now,"ready")||!Push(s.response,reply,s.hostKey))return fail(Result::Audit);
        s.phase=2;s.nextPeer=s.nextHost=2;return Result::Ok;
    }
    if(s.nextPeer==UINT64_MAX||s.nextHost==UINT64_MAX)return fail(Result::Auth);
    ++s.nextPeer;
    if(f.opcode==5){if(!json::Control(5,input))return fail(Result::Corrupt);s.Ack(5,f.request,now,"client_exit");
        s.phase=0;s.nextPeer=s.nextHost=1;sco_wipe(s.peerKey.data(),32);sco_wipe(s.hostKey.data(),32);return Result::Ok;}
    Frame reply=f;reply.direction=2;reply.sequence=s.nextHost++;
    const char* outcome="ok";
    if(!json::Read(f.opcode,input)){reply.payload=json::Error("invalid_request");outcome="invalid_request";}
    else {
        if(now-s.readStart>=60000){s.readStart=now;s.readCount=0;}
        if(!s.lastRead||now-s.lastRead>=1000)s.burst=0;s.lastRead=now;
        if(++s.readCount>60||++s.burst>5){reply.payload=json::Error("rate_limited");outcome="rate_limited";}
        else reply.payload=json::Serialize(f.opcode,input,s.snapshots,s.capture,Hex(s.credentials.session.data(),16),s.credentials.epoch,now);
    }
    if(!s.Ack(f.opcode,f.request,now,outcome,uint32_t(reply.payload.size()))) {
        reply.payload=json::Error("audit_unavailable");
        if(!Push(s.response,reply,s.hostKey))return fail(Result::Audit);
        return Result::Audit;
    }
    // Recheck deadline/transport after audit acknowledgement: no cached observation escapes revoked geometry.
    if(!s.Admitted()){Stop();s.capture.Stop();return Result::Disabled;}
    const auto completed=s.production?ClockNow():now;
    if(completed>=f.deadline)return fail(Result::Deadline);
    if(Rings(s.map,s.credentials,s.channel,s.request,s.response,completed)!=Result::Ok)return fail(Result::Corrupt);
    if(!Push(s.response,reply,s.hostKey))return fail(Result::Corrupt);return Result::Ok;
}
