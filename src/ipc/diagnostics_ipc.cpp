bool Echo(const json::Object& o,const Key& client,const Key& host) {
    const auto a=o.strings.find("client_nonce"),b=o.strings.find("host_nonce");
    return a!=o.strings.end()&&b!=o.strings.end()&&a->second==Hex(client.data(),32)&&b->second==Hex(host.data(),32);
}
Result Pop(sc_ipc_ring_view& ring,const Key& key,Frame& frame,uint32_t max) {
    std::array<uint8_t,kResponse> buffer{}; uint32_t size=max,type=0;
    const int rc=sc_ipc_ring_pop(&ring,&type,buffer.data(),&size);
    if(rc==SC_IPC_EMPTY)return Result::Empty;
    if(rc==SC_IPC_EPOCH)return Result::Epoch;
    if(rc!=SC_IPC_OK||type!=1)return Result::Corrupt;
    return Decode(buffer.data(),size,key,frame,max);
}
bool Push(sc_ipc_ring_view& ring,const Frame& frame,const Key& key) {
    auto bytes=Encode(frame,key);return !bytes.empty()&&sc_ipc_ring_push(&ring,1,bytes.data(),uint32_t(bytes.size()))==SC_IPC_OK;
}
bool Coordinates(const Frame& f,const Credentials& c,uint8_t direction,uint64_t seq,uint64_t now) {
    return f.session==c.session&&f.epoch==c.epoch&&f.direction==direction&&f.sequence==seq&&
        !Zero(f.request.data(),16)&&f.deadline>=now&&f.deadline-now<=2000;
}
Result Rings(platform::Mapping& m,const Credentials& c,sc_ipc_chan& chan,sc_ipc_ring_view& request,sc_ipc_ring_view& response,uint64_t now) {
    return Geometry(m,c,chan,request,response,now);
}
// Responses are generated by the fixed serializer. Peer additionally refuses malformed
// UTF-8 before exposing authenticated text (never promotes unsigned peer errors).
bool Utf8(std::string_view s) {
    for(size_t i=0;i<s.size();) {
        uint32_t c=static_cast<unsigned char>(s[i++]),minimum=0;unsigned n=0;
        if(c<128)continue;
        if(c>=0xc2&&c<=0xdf){c&=31;n=1;minimum=128;}
        else if(c>=0xe0&&c<=0xef){c&=15;n=2;minimum=2048;}
        else if(c>=0xf0&&c<=0xf4){c&=7;n=3;minimum=65536;}else return false;
        if(s.size()-i<n)return false;
        while(n--){auto b=static_cast<unsigned char>(s[i++]);if((b&192)!=128)return false;c=(c<<6)|(b&63);}
        if(c<minimum||c>0x10ffff||(c>=0xd800&&c<=0xdfff))return false;
    }return true;
}
