Result Peer::Begin(const std::string& path,uint64_t now) {
    auto& s=*state_;if(s.phase||s.map.base)return Result::Busy;
    if(!platform::Acquire(s.lease))return Result::Busy;
    auto fail=[&](Result r){Close();return r;};std::string credential;
    if(!platform::ReadCredential(path,credential)||!ParseCredential(credential,s.credentials)){sco_wipe(credential.data(),credential.size());return fail(Result::Auth);}sco_wipe(credential.data(),credential.size());
    if(!platform::Open(s.map))return fail(Result::Unavailable);
    const auto geometry=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(geometry!=Result::Ok)return fail(geometry);
    // Lease acquired and verified before touching any ring counter or heartbeat.
    if(sc_ipc_i_ld64(&s.request.ring->head)!=sc_ipc_i_ld64(&s.request.ring->tail)||
       sc_ipc_i_ld64(&s.response.ring->head)!=sc_ipc_i_ld64(&s.response.ring->tail))return fail(Result::Busy);
    if(now>kMaxMonotonicMs||!platform::Random(s.client.data(),32)||Zero(s.client.data(),32))return fail(Result::Auth);
    Frame f;f.opcode=1;f.session=s.credentials.session;f.epoch=s.credentials.epoch;f.sequence=0;f.direction=1;f.deadline=now+2000;
    if(!platform::Random(f.request.data(),16)||Zero(f.request.data(),16))return fail(Result::Auth);
    f.payload="{\"client_nonce\":\""+Hex(s.client.data(),32)+"\",\"expected_host_build\":"+Build(s.credentials)+"}";
    sc_ipc_peer_beat(&s.channel,0,now);if(!Push(s.request,f,s.credentials.secret))return fail(Result::Corrupt);
    s.pending=f;s.phase=1;s.lastNow=now;s.nextPeer=s.nextHost=2;return Result::Ok;
}
Result Peer::Challenge(uint64_t now) {
    auto& s=*state_;if(s.phase!=1)return Result::Unavailable;
    auto fail=[&](Result r){Close();return r;};auto g=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(g!=Result::Ok)return fail(g);
    if(now<s.lastNow||now>s.pending.deadline)return fail(Result::Deadline);
    Frame f;auto r=Pop(s.response,s.credentials.secret,f,kResponse);if(r==Result::Empty)return r;if(r!=Result::Ok)return fail(r);
    json::Object o;if(!Coordinates(f,s.credentials,2,0,now)||f.opcode!=2||f.request!=s.pending.request||f.deadline!=s.pending.deadline||
        !json::Parse(f.payload,o)||!json::Control(2,o)||o.strings.at("client_nonce")!=Hex(s.client.data(),32)||
        (o.nulls.count("host_build")!=size_t(!s.credentials.build))||(s.credentials.build&&o.strings.at("host_build")!=*s.credentials.build)||
        !Unhex(o.strings.at("host_nonce"),s.host.data(),32)||Zero(s.host.data(),32)||s.host==s.client)return fail(Result::Auth);
    Derive(s.credentials,s.client,s.host,s.peerKey,s.hostKey);s.pending.opcode=3;s.pending.sequence=1;s.pending.payload=Transcript(s.client,s.host);
    sc_ipc_peer_beat(&s.channel,0,now);if(!Push(s.request,s.pending,s.peerKey))return fail(Result::Corrupt);s.phase=2;s.lastNow=now;return Result::Ok;
}
Result Peer::Ready(uint64_t now) {
    auto& s=*state_;if(s.phase!=2)return Result::Unavailable;auto fail=[&](Result r){Close();return r;};
    auto g=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(g!=Result::Ok)return fail(g);
    if(now<s.lastNow||now>s.pending.deadline)return fail(Result::Deadline);
    Frame f;auto r=Pop(s.response,s.hostKey,f,kResponse);if(r==Result::Empty)return r;if(r!=Result::Ok)return fail(r);
    json::Object o;if(!Coordinates(f,s.credentials,2,1,now)||f.opcode!=4||f.request!=s.pending.request||f.deadline!=s.pending.deadline||
        !json::Parse(f.payload,o)||!json::Control(4,o)||!Echo(o,s.client,s.host))return fail(Result::Auth);
    s.phase=3;s.lastNow=now;s.pending={};return Result::Ok;
}
Result Peer::Send(uint16_t opcode,std::string_view input,uint64_t now) {
    auto& s=*state_;if(s.phase!=3)return s.phase==4?Result::Busy:Result::Unavailable;
    json::Object o;if(!json::Parse(input,o)||!json::Read(opcode,o))return Result::Corrupt;
    auto g=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(g!=Result::Ok){Close();return g;}
    if(now<s.lastNow||s.nextPeer==UINT64_MAX||now>kMaxMonotonicMs){Close();return Result::Deadline;}
    Frame f;f.opcode=opcode;f.session=s.credentials.session;f.epoch=s.credentials.epoch;f.sequence=s.nextPeer++;f.direction=1;f.deadline=now+2000;f.payload=input;
    if(!platform::Random(f.request.data(),16)||Zero(f.request.data(),16)){Close();return Result::Auth;}
    sc_ipc_peer_beat(&s.channel,0,now);if(!Push(s.request,f,s.peerKey)){Close();return Result::Corrupt;}s.pending=f;s.phase=4;s.lastNow=now;return Result::Ok;
}
Result Peer::Receive(uint64_t now,std::string& output) {
    output.clear();auto& s=*state_;if(s.phase!=4)return Result::Unavailable;
    auto fail=[&](Result r){Close();return r;};auto g=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);if(g!=Result::Ok)return fail(g);
    if(now<s.lastNow||now>s.pending.deadline)return fail(Result::Deadline);
    Frame f;auto r=Pop(s.response,s.hostKey,f,kResponse);if(r==Result::Empty)return r;if(r!=Result::Ok)return fail(r);
    if(!Coordinates(f,s.credentials,2,s.nextHost,now)||f.opcode!=s.pending.opcode||f.request!=s.pending.request||f.deadline!=s.pending.deadline||s.nextHost==UINT64_MAX)return fail(Result::Auth);
    ++s.nextHost;s.phase=3;s.lastNow=now;output=std::move(f.payload);s.pending={};return Result::Ok;
}
Result Peer::Heartbeat(uint64_t now){
    auto& s=*state_;if(s.phase!=3)return Result::Unavailable;
    const auto result=Rings(s.map,s.credentials,s.channel,s.request,s.response,now);
    if(result!=Result::Ok){Close();return result;}
    if(now<s.lastNow){Close();return Result::Deadline;}
    sc_ipc_peer_beat(&s.channel,0,now);s.lastNow=now;return Result::Ok;
}
