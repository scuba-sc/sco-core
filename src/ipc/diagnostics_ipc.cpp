void Mac(const Key& key,const uint8_t* bytes,size_t n,uint8_t* tag) {
    sco_hmac_sha256 mac; sco_hmac_sha256_init(&mac,key.data(),key.size());
    sco_hmac_sha256_update(&mac,kDomain,sizeof(kDomain));
    sco_hmac_sha256_update(&mac,bytes,n); sco_hmac_sha256_final(&mac,tag); sco_wipe(&mac,sizeof(mac));
}
