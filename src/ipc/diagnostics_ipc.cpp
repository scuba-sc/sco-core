Result Host::Start(const Options& options,FixtureAudit* audit,uint64_t now) {
    if(!options.enabled)return Result::Disabled;
#ifndef SCO_RUNTIME_DIAGNOSTICS_FIXTURE
    if(audit)return Result::Disabled; // fixture acknowledgements cannot authorize production
#endif
    auto& s=*state_;if(s.map.base)return Result::Busy;
    s.production = audit==nullptr;
    if(s.production){
        if(!Authorized(options.policy))return Result::Disabled;
        if(!options.policy.collector)return Result::Audit;
        const auto deadline=ClockNow()+2000;
        const auto receipt=options.policy.collector->Verify(deadline);
        if(!audit::Protected(receipt,deadline,ClockNow()))return Result::Audit;
        s.collector=options.policy.collector;
    }
    if(!Label(options.hostBuild)||now>kMaxMonotonicMs)return Result::Corrupt;
    const auto path=std::filesystem::path(options.credentialPath).lexically_normal();
    if(!path.is_absolute()||path.string()!=options.credentialPath||options.excludedRoots.empty())return Result::Unavailable;
    for(const auto& root:options.excludedRoots)if(!std::filesystem::path(root).is_absolute())return Result::Unavailable;
    for(const auto& root:options.excludedRoots){const auto relative=path.lexically_relative(std::filesystem::path(root).lexically_normal());
        if(relative.empty()||(!relative.empty()&&*relative.begin()!=".."))return Result::Unavailable;}
    s.options=options;s.audit=audit;s.lastNow=now;s.credentials={};s.credentials.build=options.hostBuild;
    if(!platform::Random(s.credentials.secret.data(),32)||!platform::Random(s.credentials.session.data(),16)||
       !platform::Random(&s.credentials.epoch,8)||!s.credentials.epoch||!platform::Create(s.map)){s.Wipe();return Result::Unavailable;}
    std::memset(s.map.base,0,kBytes);
    if(sc_ipc_init(s.map.base,kBytes,0,kMagic,1,now,&s.channel)!=SC_IPC_OK){Stop();return Result::Corrupt;}
    s.channel.epoch=s.credentials.epoch;sc_ipc_i_st64(&sc_ipc_i_hdr(&s.channel)->epoch,s.credentials.epoch);
    auto* d=static_cast<uint8_t*>(s.map.base)+64;Put(d,kMagic,4);Put(d+4,1,2);Put(d+6,64,2);std::memcpy(d+8,s.credentials.session.data(),16);
    Put(d+24,128,8);Put(d+32,33088,8);Put(d+40,4096,4);Put(d+44,65536,4);
    if(sc_ipc_ring_init(&s.channel,kRequestOffset,32768,2,&s.request)!=SC_IPC_OK||
       sc_ipc_ring_init(&s.channel,kResponseOffset,131072,1,&s.response)!=SC_IPC_OK){Stop();return Result::Corrupt;}
    s.phase=0;s.nextPeer=s.nextHost=1;s.authStart=s.readStart=now;s.authCount=s.readCount=s.burst=0;s.lastRead=0;s.nonces.clear();
    // Never delete a pre-existing credential on exclusive-creation failure.
    if(!platform::WriteCredential(options.credentialPath,Credential(s.credentials))){sc_ipc_close(&s.channel);platform::Close(s.map);s.Wipe();s.channel={};s.audit=nullptr;return Result::Unavailable;}
    if(!s.Ack(0,{},now,"opened")){Stop();return Result::Audit;}return Result::Ok;
}
