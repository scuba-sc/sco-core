std::string Hex(const uint8_t* b,size_t n) {static constexpr char h[]="0123456789abcdef";std::string s;for(size_t i=0;i<n;++i){s+=h[b[i]>>4];s+=h[b[i]&15];}return s;}
bool Unhex(std::string_view s,uint8_t* b,size_t n) {
    if(s.size()!=n*2)return false;
    for(size_t i=0;i<n;++i){unsigned v=0;for(size_t j=0;j<2;++j){char c=s[i*2+j];if(c>='0'&&c<='9')v=v*16+c-'0';else if(c>='a'&&c<='f')v=v*16+c-'a'+10;else return false;}b[i]=uint8_t(v);}return true;
}
std::vector<uint8_t> Encode(const Frame& f,const Key& key) {
    const auto max=f.direction==1?kRequest:kResponse;
    if((f.direction!=1&&f.direction!=2)||f.payload.size()>max-104)return {};
    std::vector<uint8_t>b(104+f.payload.size(),0);
    Put(b.data(),kMagic,4);Put(b.data()+4,1,2);Put(b.data()+6,f.opcode,2);
    std::memcpy(b.data()+8,f.session.data(),16);Put(b.data()+24,f.epoch,8);Put(b.data()+32,f.sequence,8);
    std::memcpy(b.data()+40,f.request.data(),16);Put(b.data()+56,f.payload.size(),4);b[60]=f.direction;Put(b.data()+64,f.deadline,8);
    std::memcpy(b.data()+72,f.payload.data(),f.payload.size());Mac(key,b.data(),b.size()-32,b.data()+b.size()-32);return b;
}
Result Decode(const uint8_t* b,size_t n,const Key& key,Frame& f,uint32_t limit) {
    f={};if(!b||n<104||n>limit||Get(b,4)!=kMagic||Get(b+4,2)!=1||!Zero(b+61,3)||
        (b[60]!=1&&b[60]!=2)||Get(b+56,4)!=n-104)return Result::Corrupt;
    Key tag{};Mac(key,b,n-32,tag.data());const bool valid=sco_ct_equal(tag.data(),b+n-32,32)!=0;sco_wipe(tag.data(),32);
    if(!valid)return Result::Auth;
    f.opcode=uint16_t(Get(b+6,2));std::memcpy(f.session.data(),b+8,16);f.epoch=Get(b+24,8);f.sequence=Get(b+32,8);
    std::memcpy(f.request.data(),b+40,16);f.direction=b[60];f.deadline=Get(b+64,8);
    f.payload.assign(reinterpret_cast<const char*>(b+72),n-104);if(!Utf8(f.payload)){f={};return Result::Corrupt;}return Result::Ok;
}
void Derive(const Credentials& c,const Key& client,const Key& host,Key& peer,Key& hostKey) {
    auto one=[&](const char* label,size_t size,Key& out){sco_hmac_sha256 mac; sco_hmac_sha256_init(&mac,c.secret.data(),32);
        sco_hmac_sha256_update(&mac,label,size);sco_hmac_sha256_update(&mac,c.session.data(),16);
        uint8_t epoch[8];Put(epoch,c.epoch,8);sco_hmac_sha256_update(&mac,epoch,8);
        sco_hmac_sha256_update(&mac,client.data(),32);sco_hmac_sha256_update(&mac,host.data(),32);
        sco_hmac_sha256_final(&mac,out.data());sco_wipe(&mac,sizeof(mac));};
    constexpr char a[]="sco.diagnostics.v1.peer",b[]="sco.diagnostics.v1.host";one(a,sizeof(a),peer);one(b,sizeof(b),hostKey);
}
std::string Credential(const Credentials& c) {
    return "{\"credential_version\":1,\"session_id\":\""+Hex(c.session.data(),16)+"\",\"secret\":\""+Hex(c.secret.data(),32)+
        "\",\"mapping_name\":"+Quote(platform::MappingName())+",\"layout_id\":826558291,\"layout_version\":1,\"epoch\":\""+std::to_string(c.epoch)+"\",\"host_build\":"+Build(c)+"}";
}
bool ParseCredential(std::string_view text,Credentials& c) {
    c={};json::Object o;if(!json::Parse(text,o)||o.integers.size()!=3||o.strings.size()+o.nulls.size()!=5||
        o.integers["credential_version"]!=1||o.integers["layout_id"]!=kMagic||o.integers["layout_version"]!=1)return false;
    for(const auto& a:o.strings)if(a.first!="session_id"&&a.first!="secret"&&a.first!="mapping_name"&&a.first!="epoch"&&a.first!="host_build")return false;
    if((!o.nulls.empty()&&o.nulls!=std::set<std::string>{"host_build"})||o.strings["mapping_name"]!=platform::MappingName()||
        !Unhex(o.strings["session_id"],c.session.data(),16)||!Unhex(o.strings["secret"],c.secret.data(),32))return false;
    const auto& e=o.strings["epoch"];if(e.empty()||e.size()>20||(e.size()>1&&e[0]=='0'))return false;
    for(char a:e){if(a<'0'||a>'9'||c.epoch>(UINT64_MAX-uint64_t(a-'0'))/10)return false;c.epoch=c.epoch*10+uint64_t(a-'0');}
    if(!c.epoch)return false;
    if(o.strings.count("host_build"))c.build=o.strings.at("host_build");
    if(!Label(c.build))return false;return true;
}
Result Geometry(platform::Mapping& m,const Credentials& c,sc_ipc_chan& chan,sc_ipc_ring_view& request,sc_ipc_ring_view& response,uint64_t now) {
    if(!m.base||m.bytes!=kBytes)return Result::Corrupt;
    auto* base=static_cast<uint8_t*>(m.base);sc_ipc_hdr h{};sc_ipc_i_copy_out(&h,base,64);
    if(h.epoch!=c.epoch)return Result::Epoch;
    if(h.magic!=SC_IPC_MAGIC||h.version!=1||h.bytes!=kBytes||h.layout_id!=kMagic||h.layout_version!=1||h.reserved||h.state!=1)return Result::Corrupt;
    if(h.owner_heartbeat_ms>now||h.peer_heartbeat_ms>now)return Result::Corrupt;
    if(now-h.owner_heartbeat_ms>5000||(h.peer_heartbeat_ms&&now-h.peer_heartbeat_ms>5000))return Result::Deadline;
    std::array<uint8_t,64>d{};sc_ipc_i_copy_out(d.data(),base+64,64);
    if(Get(d.data(),4)!=kMagic||Get(d.data()+4,2)!=1||Get(d.data()+6,2)!=64||
       !sco_ct_equal(d.data()+8,c.session.data(),16)||Get(d.data()+24,8)!=128||Get(d.data()+32,8)!=33088||
       Get(d.data()+40,4)!=4096||Get(d.data()+44,4)!=65536||!Zero(d.data()+48,16))return Result::Corrupt;
    // Validate fixed geometry; never use peer-supplied offsets/capacities to address memory.
    for(unsigned i=0;i<2;++i){sc_ipc_ring r{};sc_ipc_i_copy_out(&r,base+(i?33088:128),192);
        const uint64_t cap=i?131072:32768;
        if(r.magic!=SC_IPC_RING_MAGIC||r.direction!=(i?1u:2u)||r.capacity!=cap||r.epoch!=c.epoch||
           !Zero(r.pad0,sizeof(r.pad0))||!Zero(r.pad1,sizeof(r.pad1))||!Zero(r.pad2,sizeof(r.pad2))||
           ((r.head|r.tail)&7)||r.head<r.tail||r.head-r.tail>cap||r.pushed<r.popped||r.pushed-r.popped>8||
           r.head>UINT64_MAX-cap||r.pushed==UINT64_MAX||r.popped==UINT64_MAX)return Result::Corrupt;
    }
    // Reserved bytes are never executable/bulk payload or a second channel.
    for(uint64_t i=164352;i<kBytes;++i)if(sc_ipc_i_ld8r(base+i))return Result::Corrupt;
    if(!chan.base){if(sc_ipc_attach(m.base,m.bytes,kMagic,1,&chan)!=SC_IPC_OK||
        sc_ipc_ring_attach(&chan,128,&request)!=SC_IPC_OK||sc_ipc_ring_attach(&chan,33088,&response)!=SC_IPC_OK)return Result::Corrupt;}
    return Result::Ok;
}
struct Host::State {
    SnapshotStore& snapshots;Capture& capture;FixtureAudit* audit=nullptr;Options options;
    std::shared_ptr<audit::Collector> collector; bool production=false;
    uint64_t ackDeadline=0,deniedCount=0,lastDeniedAudit=0;
    // Permanent host token only: never a sco_plugin* or public C table route.
    const void* owner=sco::host::HostOwner(); platform::Mapping map; Credentials credentials;
    sc_ipc_chan channel{};sc_ipc_ring_view request{},response{};
    Key client{},host{},peerKey{},hostKey{};std::set<std::string> nonces;
    int phase=0;uint64_t nextPeer=1,nextHost=1,lastNow=0,authStart=0,readStart=0,lastRead=0,handshakeDeadline=0;
    uint32_t authCount=0,readCount=0,burst=0;Id handshakeId{};
    explicit State(SnapshotStore& s,Capture& c):snapshots(s),capture(c){}
    bool Admitted() const { return !production || Authorized(options.policy); }
    bool Ack(uint16_t op,const Id& id,uint64_t now,const char* outcome,uint32_t bytes=0){
        if(!production)return audit&&audit->Acknowledge({op,id,now,bytes,outcome});
        if(!collector)return false;
        const bool denial=std::strcmp(outcome,"rate_limited")==0;
        if(denial){++deniedCount;if(lastDeniedAudit&&now-lastDeniedAudit<1000)return true;}
        audit::Coordinates coordinates;coordinates.session=credentials.session;
        coordinates.build=credentials.build.value_or("unknown");
        coordinates.aggregateCount=denial?deniedCount:1;
        const auto deadline=ackDeadline?ackDeadline:ClockNow()+2000;
        const auto receipt=collector->Append({op,id,now,bytes,outcome},coordinates,deadline);
        const bool accepted=audit::Acknowledged(receipt,deadline,ClockNow());
        if(accepted&&denial){deniedCount=0;lastDeniedAudit=now;}
        return accepted;
    }
    void Wipe(){sco_wipe(credentials.secret.data(),32);sco_wipe(client.data(),32);sco_wipe(host.data(),32);sco_wipe(peerKey.data(),32);sco_wipe(hostKey.data(),32);}
};
