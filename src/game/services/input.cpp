bool started = false;
sco_result Check(sco_plugin* self) {
    if (!OnGameThread()) return SCO_WRONG_THREAD;
    if (!host::PluginId(self) || detail::Released(self)) return SCO_BAD_ARG;
    return started && !detail::RuntimeStopping() ? SCO_OK : SCO_UNAVAILABLE;
}
void Copy(const Action& action, sc_input_action_info* out) {
    const uint32_t size = out->size;
    *out = {};
    out->size = size;
    out->id = action.id;
    out->flags = action.flags;
    std::memcpy(out->name, action.name, std::strlen(action.name) + 1);
}
sco_result Count(sco_plugin* self, uint32_t* out) {
    const sco_result r = Check(self);
    if (r != SCO_OK) return r;
    if (!out) return SCO_BAD_ARG;
    *out = SC_INPUT_ACTION_COUNT;
    return SCO_OK;
}
sco_result ById(sco_plugin* self, uint32_t id, sc_input_action_info* out) {
    const sco_result r = Check(self);
    if (r != SCO_OK) return r;
    if (!out || out->size < sizeof(*out)) return SCO_BAD_ARG;
    if (id >= std::size(actions) - 1) return SCO_NOT_FOUND;
    Copy(actions[id], out);
    return SCO_OK;
}
sco_result ByName(sco_plugin* self, const char* name, sc_input_action_info* out) {
    const sco_result r = Check(self);
    if (r != SCO_OK) return r;
    if (!name || !out || out->size < sizeof(*out)) return SCO_BAD_ARG;
    size_t len = 0;
    for (; len < SC_INPUT_ACTION_NAME_BYTES && name[len]; ++len) {}
    if (!len || len == SC_INPUT_ACTION_NAME_BYTES) return SCO_BAD_ARG;
    size_t first = 0, last = std::size(byName);
    while (first < last) {
        const size_t mid = first + (last - first) / 2;
        const Action& a = actions[byName[mid]];
        const int cmp = std::strcmp(name, a.name);
        if (!cmp) { Copy(a, out); return SCO_OK; }
        if (cmp < 0) last = mid;
        else first = mid + 1;
    }
    return SCO_NOT_FOUND;
}
const sc_input_v1 table = {sizeof(sc_input_v1), 0, Count, ById, ByName};
