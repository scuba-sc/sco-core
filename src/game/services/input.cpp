Result StartInput() {
    if (!OnGameThread()) return Result::WrongThread;
    if (started) return Result::Ok;
    const Result r = host::ProvideGameService(SC_INPUT_SERVICE_NAME, SC_INPUT_SERVICE_VERSION, &table);
    started = r == Result::Ok;
    if (started) caps::Set("game.input.registry", true, "static metadata; not live input");
    return r;
}
void StopInput() {
    if (!OnGameThread() || !started) return;
    host::WithdrawGameService(SC_INPUT_SERVICE_NAME);
    caps::Set("game.input.registry", false, "input registry stopped");
    started = false;
}
