static const char* const kPanelBuilderSource[] = {
    "local type, next, rawget, error, pcall = type, next, rawget, error, pcall\n"
    "local utf8len, huge = utf8.len, math.huge\n"
    "local fields = {\n"
    "  column={label=true, disabled=true}, row={label=true, disabled=true},\n"
    "  button={label=true, disabled=true, on_click=true},\n"
    "  toggle={label=true, disabled=true, value=true, on_change=true},\n"
    "  slider={label=true, disabled=true, value=true, minimum=true, maximum=true, on_change=true}\n"
    "}\n"
    "local function check(ok, message)\n"
    "  if not ok then error('panel_builder: '..message, 3) end\n"
    "end\n"
    "local function finite(v)\n"
    "  return type(v)=='number' and v > -huge and v < huge\n"
    "end\n"
    "local function node(kind, options)\n"
    "  check(type(options)=='table', 'options must be a table')\n"
    "  for key in next, options do\n"
    "    check(fields[kind][key], 'unknown option')\n"
    "  end\n"
    "  local label, disabled = rawget(options, 'label'), rawget(options, 'disabled')\n"
    "  local layout = kind=='column' or kind=='row'\n"
    "  if label~=nil or not layout then\n"
    "    check(type(label)=='string' and #label<=255 and not label:find('\\0', 1, true)\n"
    "      and utf8len(label)~=nil and (layout or #label>0), 'invalid label')\n"
    "  end\n"
    "  check(disabled==nil or type(disabled)=='boolean', 'disabled must be boolean')\n"
    "  local n = {kind=kind, label=label, disabled=disabled}\n"
    "  local callback = rawget(options, kind=='button' and 'on_click' or 'on_change')\n"
    "  check(callback==nil or type(callback)=='function', 'callback must be a function')\n"
    "  if kind=='toggle' then\n"
    "    local value = rawget(options, 'value')\n"
    "    check(value==nil or type(value)=='boolean', 'toggle value must be boolean')\n"
    "    n.value = value or false\n"
    "  elseif kind=='slider' then\n"
    "    local value, minimum, maximum = rawget(options, 'value'), rawget(options, 'minimum'), rawget(options, 'maximum')\n"
    "    check(finite(value) and finite(minimum) and finite(maximum)\n"
    "      and minimum<=value and value<=maximum, 'invalid slider range/value')\n"
    "    n.value, n.minimum, n.maximum = value, minimum, maximum\n"
    "  end\n"
    "  return n, callback\n"
    "end\n",
    "local M = {}\n"
    "function M.new()\n"
    "  local records, parent, enabled = {}, 0, true\n"
    "  local b = {}\n"
    "  local function append(kind, options)\n"
    "    local n, callback = node(kind, options)\n"
    "    check(#records<256, 'too many nodes')\n"
    "    n.id, n.parent = #records+1, parent\n"
    "    records[n.id] = {node=n, callback=callback, enabled=enabled and not n.disabled}\n"
    "    return n.id\n"
    "  end\n"
    "  local function scope(kind, fn, options)\n"
    "    check(type(fn)=='function', 'layout body must be a function')\n"
    "    local oldparent, oldenabled, count = parent, enabled, #records\n"
    "    if options==nil then options={} end\n"
    "    local id = append(kind, options)\n"
    "    parent, enabled = id, records[id].enabled\n"
    "    local ok, message = pcall(fn, b)\n"
    "    parent, enabled = oldparent, oldenabled\n"
    "    if not ok then\n"
    "      for i=#records,count+1,-1 do records[i]=nil end\n"
    "      error(message, 0)\n"
    "    end\n"
    "    return id\n"
    "  end\n"
    "  function b:column(fn, options) return scope('column', fn, options) end\n"
    "  function b:row(fn, options) return scope('row', fn, options) end\n"
    "  function b:button(options) return append('button', options) end\n"
    "  function b:toggle(options) return append('toggle', options) end\n"
    "  function b:slider(options) return append('slider', options) end\n"
    "  function b:build()\n"
    "    check(parent==0, 'cannot build inside a layout body')\n"
    "    check(#records>0, 'empty panel')\n"
    "    local nodes, callbacks = {}, {}\n"
    "    for i=1,#records do\n"
    "      local record, copy = records[i], {}\n"
    "      for key,value in next, record.node do copy[key]=value end\n"
    "      nodes[i] = copy\n"
    "      if record.callback and record.enabled then\n"
    "        callbacks[i] = {kind=copy.kind, fn=record.callback}\n"
    "      end\n"
    "    end\n"
    "    return nodes, function(panel, event)\n"
    "      local callback = callbacks[event.node_id]\n"
    "      if not callback or callback.kind~=event.kind then return false end\n"
    "      callback.fn(panel, event)\n"
    "      return true\n"
    "    end\n"
    "  end\n"
    "  return b\n"
    "end\n"
    "return M\n"
};
