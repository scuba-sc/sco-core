/* Game thread, live self. Metadata only. count is the number of named actions;
 * every id 1..count has exactly one name, and there are no sentinel records.
 * size must cover the full record; structural failure leaves outputs unchanged.
 * Unknown id/name returns NOT_FOUND. Names are exact, case-sensitive ASCII. */
typedef struct sc_input_v1 {
    uint32_t size;
    uint32_t _pad;
    sco_result (*count)(sco_plugin* self, uint32_t* out);
    sco_result (*by_id)(sco_plugin* self, uint32_t id, sc_input_action_info* out);
    sco_result (*by_name)(sco_plugin* self, const char* name, sc_input_action_info* out);
} sc_input_v1;
